/**
 * Keeps this repository's copy of the backend API contract up to date.
 *
 *   pnpm api:sync                       download from the running backend
 *   pnpm api:sync -- --from <path|url>  use another source, e.g. a file from the backend team
 *   pnpm api:check                      only check that the generated types match openapi.json (CI)
 *
 * What it does:
 *   1. gets the contract (OpenAPI JSON) from the backend,
 *   2. saves it as packages/api/openapi.json (committed, so everyone builds against the same API),
 *   3. generates TypeScript types from it into src/generated/openapi.ts.
 *
 * After a sync, run `pnpm typecheck`: every screen that uses a changed endpoint shows an error.
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractFile = join(packageDir, 'openapi.json');
const typesFile = join(packageDir, 'src', 'generated', 'openapi.ts');
const HEADER = '// Generated by packages/api/scripts/sync.mjs from openapi.json. Do not edit.\n';

const args = process.argv.slice(2);
const checkOnly = args.includes('--check');
const fromIndex = args.indexOf('--from');
const source =
  fromIndex >= 0
    ? args[fromIndex + 1]
    : (process.env.API_CONTRACT_URL ?? 'http://localhost:3000/api/docs/openapi.json');

/** Types generated from a contract, as the file content we write. */
async function generateTypes(contract) {
  return HEADER + astToString(await openapiTS(contract));
}

async function readContract(from) {
  if (/^https?:\/\//.test(from)) {
    let response;
    try {
      response = await fetch(from);
    } catch {
      throw new Error(
        `Could not reach ${from}. Start the backend (pnpm dev in the backend repository), ` +
          'or use: pnpm api:sync -- --from <path to openapi.json>',
      );
    }
    if (!response.ok) throw new Error(`${from} answered ${response.status}`);
    return response.json();
  }
  // pnpm runs this script inside packages/api; INIT_CWD is the folder where you typed the
  // command, so relative paths mean what you expect.
  const path = resolve(process.env.INIT_CWD ?? process.cwd(), from);
  if (!existsSync(path)) throw new Error(`File not found: ${path}`);
  return JSON.parse(readFileSync(path, 'utf8'));
}

function countOperations(contract) {
  const methods = ['get', 'put', 'post', 'delete', 'patch'];
  return Object.values(contract.paths ?? {}).reduce(
    (sum, item) => sum + methods.filter((m) => item[m]).length,
    0,
  );
}

async function main() {
  if (checkOnly) {
    const contract = JSON.parse(readFileSync(contractFile, 'utf8'));
    const expected = await generateTypes(contract);
    const actual = existsSync(typesFile) ? readFileSync(typesFile, 'utf8') : '';
    if (expected !== actual) {
      console.error('src/generated/openapi.ts does not match openapi.json. Run: pnpm api:sync');
      process.exit(1);
    }
    console.log('API types match openapi.json.');
    return;
  }

  const contract = await readContract(source);
  if (typeof contract.openapi !== 'string' || !contract.paths) {
    throw new Error(`${source} is not an OpenAPI document`);
  }

  writeFileSync(contractFile, JSON.stringify(contract, null, 2) + '\n');
  mkdirSync(dirname(typesFile), { recursive: true });
  writeFileSync(typesFile, await generateTypes(contract));

  console.log(
    `Synced API contract ${contract.info?.version ?? ''} (${countOperations(contract)} operations) ` +
      `from ${source}. Next: pnpm typecheck`,
  );
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
